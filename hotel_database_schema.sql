-- -----------------------------------------------------------------------------
-- HÀM TRIGGER TỰ ĐỘNG CẬP NHẬT CỘT updated_at
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =============================================================================
-- 1. BẢNG PHÒNG KHÁCH SẠN (rooms)
-- =============================================================================
CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) UNIQUE NOT NULL,
    floor INT NOT NULL DEFAULT 1,
    room_type VARCHAR(50) NOT NULL DEFAULT 'Phòng Đơn',
    is_double_room BOOLEAN NOT NULL DEFAULT FALSE,
    hourly_rate_base NUMERIC(12, 2) NOT NULL DEFAULT 80000,
    hourly_rate_extra NUMERIC(12, 2) NOT NULL DEFAULT 20000,
    overnight_single_rate NUMERIC(12, 2) NOT NULL DEFAULT 200000,
    overnight_double_rate NUMERIC(12, 2) NOT NULL DEFAULT 350000,
    daily_single_rate NUMERIC(12, 2) NOT NULL DEFAULT 350000,
    daily_double_rate NUMERIC(12, 2) NOT NULL DEFAULT 500000,
    status VARCHAR(20) NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'occupied', 'cleaning', 'maintenance')),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TRIGGER trigger_rooms_updated_at
    BEFORE UPDATE ON rooms
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

-- =============================================================================
-- 2. BẢNG PHIÊN THUÊ PHÒNG & HÓA ĐƠN (bookings)
-- =============================================================================
CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT REFERENCES rooms(id) ON DELETE SET NULL,
    room_number VARCHAR(20) NOT NULL,
    customer_name VARCHAR(150) DEFAULT 'Khách vãng lai',
    customer_phone VARCHAR(30),
    rental_type VARCHAR(20) NOT NULL DEFAULT 'hourly' CHECK (rental_type IN ('hourly', 'overnight', 'daily')),
    room_rate_mode VARCHAR(20) NOT NULL DEFAULT 'single' CHECK (room_rate_mode IN ('single', 'double')),
    expected_check_in TIMESTAMPTZ,
    check_in TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    check_out TIMESTAMPTZ,
    beer_qty INT NOT NULL DEFAULT 0,          -- 20.000đ/lon
    water_qty INT NOT NULL DEFAULT 0,         -- 10.000đ/chai
    soft_drink_qty INT NOT NULL DEFAULT 0,    -- 15.000đ/lon
    room_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    service_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    surcharge_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    surcharge_reason VARCHAR(255),
    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    paid_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    balance_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    payment_method VARCHAR(20) DEFAULT 'cash' CHECK (payment_method IN ('cash', 'transfer', 'split')),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'cancelled', 'reserved')),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TRIGGER trigger_bookings_updated_at
    BEFORE UPDATE ON bookings
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_bookings_room_number ON bookings(room_number);
CREATE INDEX IF NOT EXISTS idx_bookings_status ON bookings(status);
CREATE INDEX IF NOT EXISTS idx_bookings_check_in ON bookings(check_in);
CREATE INDEX IF NOT EXISTS idx_bookings_created_at ON bookings(created_at);

-- =============================================================================
-- 3. BẢNG PHIẾU CỌC GIỮ PHÒNG (reservations)
-- =============================================================================
CREATE TABLE IF NOT EXISTS reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT REFERENCES rooms(id) ON DELETE SET NULL,
    room_number VARCHAR(20) DEFAULT '',
    customer_name VARCHAR(150) NOT NULL DEFAULT 'Khách đặt cọc',
    customer_phone VARCHAR(30),
    rental_type VARCHAR(20) NOT NULL DEFAULT 'daily' CHECK (rental_type IN ('hourly', 'overnight', 'daily')),
    expected_check_in TIMESTAMPTZ NOT NULL,
    deposit_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    deposit_method VARCHAR(20) NOT NULL DEFAULT 'transfer' CHECK (deposit_method IN ('transfer', 'cash')),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'arrived', 'completed', 'cancelled')),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TRIGGER trigger_reservations_updated_at
    BEFORE UPDATE ON reservations
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_reservations_status ON reservations(status);
CREATE INDEX IF NOT EXISTS idx_reservations_expected_check_in ON reservations(expected_check_in);

-- =============================================================================
-- 4. BẢNG GIAO DỊCH DÒNG TIỀN / SỔ QUỸ PAYMENTS (payments)
-- =============================================================================
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES bookings(id) ON DELETE SET NULL,
    reservation_id BIGINT REFERENCES reservations(id) ON DELETE SET NULL,
    room_number VARCHAR(20),
    payment_type VARCHAR(20) NOT NULL DEFAULT 'settlement' CHECK (payment_type IN ('advance', 'settlement', 'deposit', 'refund', 'expense')),
    method VARCHAR(20) NOT NULL DEFAULT 'cash' CHECK (method IN ('cash', 'transfer')),
    amount NUMERIC(12, 2) NOT NULL, -- Dương = Thu vào, Âm = Rút/Chi/Thối ra
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_payments_booking_id ON payments(booking_id);
CREATE INDEX IF NOT EXISTS idx_payments_reservation_id ON payments(reservation_id);
CREATE INDEX IF NOT EXISTS idx_payments_payment_type ON payments(payment_type);
CREATE INDEX IF NOT EXISTS idx_payments_method ON payments(method);
CREATE INDEX IF NOT EXISTS idx_payments_created_at ON payments(created_at);

