-- View 1: Báo cáo dòng tiền theo ngày (Net Cash, Net Transfer, Tổng thực thu)
CREATE OR REPLACE VIEW view_daily_cashflow AS
SELECT 
    DATE(p.created_at) AS report_date,
    SUM(CASE WHEN p.method = 'cash' AND p.payment_type != 'expense' THEN p.amount ELSE 0 END) AS cash_inflow,
    SUM(CASE WHEN p.method = 'cash' AND p.amount < 0 THEN ABS(p.amount) ELSE 0 END) AS cash_outflow,
    SUM(CASE WHEN p.method = 'cash' THEN p.amount ELSE 0 END) AS net_cash,
    SUM(CASE WHEN p.method = 'transfer' THEN p.amount ELSE 0 END) AS net_transfer,
    SUM(p.amount) AS total_revenue_recognized,
    COUNT(p.id) AS total_transactions
FROM payments p
GROUP BY DATE(p.created_at)
ORDER BY report_date DESC;

-- View 2: Báo cáo tổng hợp tiêu thụ Minibar nước uống
CREATE OR REPLACE VIEW view_minibar_summary AS
SELECT 
    DATE(b.created_at) AS report_date,
    SUM(b.beer_qty) AS total_beer,
    SUM(b.water_qty) AS total_water,
    SUM(b.soft_drink_qty) AS total_soft_drink,
    SUM(b.beer_qty * 20000 + b.water_qty * 10000 + b.soft_drink_qty * 15000) AS total_minibar_revenue
FROM bookings b
GROUP BY DATE(b.created_at)
ORDER BY report_date DESC;

-- View 3: Danh sách phòng đang hoạt động (Active Bookings)
CREATE OR REPLACE VIEW view_active_rooms AS
SELECT 
    r.id AS room_id,
    r.room_number,
    r.floor,
    r.status AS room_status,
    b.id AS active_booking_id,
    b.customer_name,
    b.customer_phone,
    b.rental_type,
    b.check_in,
    b.paid_amount AS advance_paid
FROM rooms r
LEFT JOIN bookings b ON r.room_number = b.room_number AND b.status = 'active';
